#!/usr/bin/env node
/**
 * Generate the TypeScript contracts from the Rust types.
 *
 * Every serde-derived type in the contract crates also derives `ts_rs::TS`
 * behind the `ts` feature. Running their export tests writes one `.ts` file
 * per type under packages/contracts/src/generated/<crate>/, and this script
 * then writes the barrel files. CI runs it and fails when the committed
 * output differs, so the handwritten contracts in src/index.ts are checked
 * against the generated truth by src/drift.ts.
 */
import { spawnSync } from "node:child_process";
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "packages", "contracts", "src", "generated");

const crates = [
  "asten-ir",
  "asten-time",
  "asten-diagnostics",
  "asten-ls",
  "asten-blocks",
  "asten-auth",
  "asten-domain",
  "asten-application",
];

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const cargo = spawnSync(
  "cargo",
  [
    "test",
    "--features",
    "ts",
    ...crates.flatMap((crate) => ["-p", crate]),
    "--",
    "export_bindings",
  ],
  {
    cwd: root,
    stdio: "inherit",
    env: { ...process.env, TS_RS_EXPORT_DIR: outDir },
    shell: process.platform === "win32",
  },
);
if (cargo.status !== 0) {
  console.error("cargo test (ts export) failed");
  process.exit(cargo.status ?? 1);
}

const header =
  "// Generated by scripts/contracts-gen.mjs from the Rust types. Do not edit.\n";

// ts-rs renders 64-bit integers as `bigint`, but the API serialises them as
// JSON numbers and the desk reads them as `number`. Rewrite in place.
let rewritten = 0;
for (const namespace of readdirSync(outDir)) {
  const dir = join(outDir, namespace);
  if (!statSync(dir).isDirectory()) continue;
  for (const name of readdirSync(dir)) {
    const file = join(dir, name);
    const text = readFileSync(file, "utf8");
    const fixed = text.replace(/\bbigint\b/g, "number");
    if (fixed !== text) {
      writeFileSync(file, fixed);
      rewritten += 1;
    }
  }
}

const namespaces = readdirSync(outDir)
  .filter((name) => statSync(join(outDir, name)).isDirectory())
  .sort();

for (const namespace of namespaces) {
  const dir = join(outDir, namespace);
  const files = readdirSync(dir)
    .filter((name) => name.endsWith(".ts") && name !== "index.ts")
    .sort((a, b) => a.localeCompare(b, "en"));
  const barrel =
    header +
    files.map((name) => `export * from "./${name.replace(/\.ts$/, "")}";`).join("\n") +
    "\n";
  writeFileSync(join(dir, "index.ts"), barrel);
}

writeFileSync(
  join(outDir, "index.ts"),
  header +
    namespaces.map((name) => `export * as ${name} from "./${name}";`).join("\n") +
    "\n",
);

const count = namespaces.reduce(
  (sum, name) => sum + readdirSync(join(outDir, name)).length - 1,
  0,
);
console.log(
  `Generated ${count} types in ${namespaces.length} namespaces at ${outDir} (${rewritten} files had bigint rewritten to number)`,
);
