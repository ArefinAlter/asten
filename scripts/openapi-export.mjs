#!/usr/bin/env node
/**
 * Export the OpenAPI document and refresh the route table in docs/API.md.
 *
 * The document is generated at compile time in services/asten-api from the
 * `#[utoipa::path]` annotation on every handler and the `ToSchema` derives on
 * the contract crates. Running the API's export test with ASTEN_OPENAPI_OUT
 * set writes it to docs/openapi.json; without the variable the same test
 * fails when the committed file is stale, so `cargo test -p asten-api` keeps
 * the two in step. This script then rewrites the table between the
 * `<!-- routes:start -->` and `<!-- routes:end -->` markers in docs/API.md.
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const document = join(root, "docs", "openapi.json");
const guide = join(root, "docs", "API.md");

const cargo = spawnSync(
  "cargo",
  ["test", "-p", "asten-api", "--quiet", "--", "the_committed_document_is_current"],
  {
    cwd: root,
    stdio: "inherit",
    env: { ...process.env, ASTEN_OPENAPI_OUT: document },
    shell: process.platform === "win32",
  },
);
if (cargo.status !== 0) {
  console.error("cargo test (openapi export) failed");
  process.exit(cargo.status ?? 1);
}

const api = JSON.parse(readFileSync(document, "utf8"));
const methods = ["get", "post", "put", "delete", "patch"];
const tagOrder = api.tags.map((tag) => tag.name);
const rows = [];
for (const [path, item] of Object.entries(api.paths)) {
  for (const method of methods) {
    const operation = item[method];
    if (!operation) continue;
    const auth = operation.security
      ? operation.security.some((requirement) => Object.keys(requirement).length === 0)
        ? "optional"
        : "token"
      : "public";
    rows.push({
      tag: operation.tags?.[0] ?? "",
      method: method.toUpperCase(),
      path,
      summary: operation.summary ?? "",
      auth,
    });
  }
}
rows.sort(
  (a, b) =>
    tagOrder.indexOf(a.tag) - tagOrder.indexOf(b.tag) ||
    a.path.localeCompare(b.path, "en") ||
    methods.indexOf(a.method.toLowerCase()) - methods.indexOf(b.method.toLowerCase()),
);

const escape = (text) => text.replaceAll("|", "\\|");
const table = [
  "| Tag | Method | Path | Summary | Auth |",
  "| --- | --- | --- | --- | --- |",
  ...rows.map(
    (row) =>
      `| ${row.tag} | \`${row.method}\` | \`${escape(row.path)}\` | ${escape(row.summary)} | ${row.auth} |`,
  ),
].join("\n");

const start = "<!-- routes:start -->";
const end = "<!-- routes:end -->";
const text = readFileSync(guide, "utf8");
const from = text.indexOf(start);
const to = text.indexOf(end);
if (from < 0 || to < 0 || to < from) {
  console.error(`docs/API.md needs the ${start} and ${end} markers`);
  process.exit(1);
}
const schemas = Object.keys(api.components?.schemas ?? {}).length;
const generated =
  `${start}\n` +
  `<!-- Generated by scripts/openapi-export.mjs from docs/openapi.json: ` +
  `${rows.length} operations, ${schemas} schemas. Do not edit by hand. -->\n\n` +
  `${table}\n\n`;
writeFileSync(guide, text.slice(0, from) + generated + text.slice(to));
console.log(
  `Wrote ${rows.length} operations and ${schemas} schemas to docs/openapi.json and the route table in docs/API.md`,
);
